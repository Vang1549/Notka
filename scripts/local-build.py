"""Build in the approved tools folder; never publish or alter released dist files."""
import hashlib,json,os,shutil,subprocess,sys
from pathlib import Path

project=Path(sys.argv[1]).resolve();tools=Path(sys.argv[2]).resolve();stage=tools/'build'
if stage.exists():
    if stage.resolve().parent!=tools or not (stage/'.notka-build-workspace').is_file():
        raise SystemExit('Refusing to clean an unrecognized build directory')
    shutil.rmtree(stage)
stage.mkdir();(stage/'.notka-build-workspace').write_text('Generated by Notka local-build.py\n')
for folder in ['source','scripts','dist']:
    shutil.copytree(project/folder,stage/folder,ignore=shutil.ignore_patterns('node_modules','.native-build','.native-tools','__pycache__','*.pyc','signing.pem') if folder!='dist' else None)
shutil.copy2(project/'publication.json',stage/'publication.json')
source=stage/'source'
for folder in ['android','npm']: (tools/folder).mkdir(exist_ok=True)
for name in ['package.json','package-lock.json']:shutil.copy2(source/name,tools/'npm'/name)
lockhash=hashlib.sha256((source/'package-lock.json').read_bytes()).hexdigest()
stamp=tools/'npm'/'installed-lock.sha256'
if not stamp.exists() or stamp.read_text()!=lockhash or not (tools/'npm/node_modules').is_dir():
    raise SystemExit('Run scripts/build-local.ps1 to prepare locked dependencies through Windows networking')
for dest,target in [('node_modules',tools/'npm/node_modules'),('.native-tools',tools/'android')]:
    shutil.copytree(target,source/dest)
shutil.copy2(project/'dist/Notka-68.apk',source/'Notka-0.68.apk')
release=json.loads((source/'release.json').read_text())
log=(stage/'checks.log').open('w',encoding='utf8')
def run(args,cwd=source):
    print('Running '+' '.join(args),flush=True)
    p=subprocess.Popen(args,cwd=cwd,stdout=subprocess.PIPE,stderr=subprocess.STDOUT,text=True,bufsize=1)
    for line in p.stdout:print(line,end='',flush=True);log.write(line);log.flush()
    if p.wait():raise RuntimeError('Failed: '+' '.join(args))
try:run([sys.executable,'build.py'])
finally:
    if (source/'.native-tools').exists():shutil.copytree(source/'.native-tools',tools/'android',dirs_exist_ok=True)
run([sys.executable,'verify.py'])
run([sys.executable,'publish_release.py','../dist',str(release['apk_code']),release['apk_version'],'--panel-code','60','--panel-version','0.60'])
if '--skip-tests' not in sys.argv:
    for name in ['test-signing.py','test-native.py','test-background-service.py','test-update-origin.py','test-bundles.py']:
        run([sys.executable,name])
    for name in ['test-launcher.cjs','test-update.cjs','test-catalog.cjs','test-bundle-panel.cjs','test-lazy-modules.cjs','test-library-preview.cjs']:
        run(['node',name])
    run([sys.executable,'scripts/publish.py','--verify-only'],stage)
output=project/'outputs'/('local-'+release['apk_version']);output.mkdir(parents=True,exist_ok=True)
apk=source/('Notka-'+release['apk_version']+'.apk');shutil.copy2(apk,output/apk.name)
shutil.copy2(source/'.native-build/editor-builtin.zip',output/('editor-'+release['editor_version']+'.zip'))
shutil.copy2(source/'signing.der',output/'signing-public.der')
shutil.copy2(source/'app/index.html',project/'source/app/index.html')
report={'apk_version':release['apk_version'],'editor_version':release['editor_version'],'apk_sha256':hashlib.sha256(apk.read_bytes()).hexdigest(),'certificate_sha256':hashlib.sha256((source/'signing.der').read_bytes()).hexdigest(),'automated_checks':('--skip-tests' not in sys.argv),'android_device_tested':False,'published':False,'staged_update_files':str(stage/'dist'),'private_key_in_outputs':False}
(output/'build-report.json').write_text(json.dumps(report,indent=2)+'\n')
log.close();shutil.copy2(stage/'checks.log',output/'checks.log')
print('LOCAL BUILD READY: '+str(output),flush=True)
